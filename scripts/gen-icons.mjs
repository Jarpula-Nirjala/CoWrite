// Writes client/src/lib/mdi.ts: only the Material icons the app uses, copied from @mdi/js.
// @mdi/js is one 3 MB module with every icon; importing it directly made the production build need
// more memory than Render's free plan gives a build. Run `npm run icons` after using a new icon.
import fs from 'node:fs';
import path from 'node:path';
import * as all from '@mdi/js';

const SRC = 'client/src';
const OUT = path.join(SRC, 'lib', 'mdi.ts');
const used = new Set();
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(e.name) && path.resolve(p) !== path.resolve(OUT)) for (const m of fs.readFileSync(p, 'utf8').matchAll(/\bmdi[A-Z][A-Za-z0-9]*/g)) used.add(m[0]);
  }
};
walk(SRC);
const names = [...used].filter((n) => typeof all[n] === 'string').sort();
const unknown = [...used].filter((n) => typeof all[n] !== 'string');
if (unknown.length) console.warn('Not in @mdi/js (ignored):', unknown.join(', '));
const body = names.map((n) => `export const ${n} = '${all[n]}';`).join('\n');
fs.writeFileSync(OUT, `/* Generated by scripts/gen-icons.mjs from @mdi/js (Apache-2.0): the Material icons CoWrite uses. Do not edit; run \`npm run icons\`. */\n${body}\n`);
console.log(`${names.length} icons written to ${OUT}`);
